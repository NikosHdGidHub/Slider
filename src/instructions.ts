export function download(
  name: string,
  content: string,
  mime = 'application/json'
) {
  const file = new Blob([content], { type: mime + ';charset=utf-8' }),
    url = URL.createObjectURL(file),
    a = document.createElement('a')
  a.href = url
  a.download = name
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 5000)
}
